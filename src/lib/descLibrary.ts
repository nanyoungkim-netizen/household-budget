// '이체'라는 글자만으로 이체 처리하면 "우리카드 자동이체", "LGU+통신요금 자동이체"처럼
// 실제로는 지출인 자동납부가 전부 이체로 잡힌다. 지출 신호가 함께 있으면 이체에서 제외한다.
const TRANSFER_KW = ['이체', '송금', '계좌이동', '계좌간', '모임통장', '잔돈모으기', '달러로모으기', '외화저축']

const NOT_TRANSFER_KW = [
  // 카드대금 자동납부
  '카드', '카드대금',
  // 통신·공과금·보험 자동납부
  '통신', '요금', '전기', '가스', '수도', '관리비', '보험', '연금', '건강보험',
  // 대출 상환
  '대출', '원리금', '상환', '이자납부',
  // 세금
  '국세', '지방세', '세금',
]

/** 적요가 '계좌 간 이동(이체)'로 보이는지. 지출 신호가 있으면 false. */
export function isTransferDesc(desc: string, txType = ''): boolean {
  const s = normalizeDesc(desc + txType)
  if (!TRANSFER_KW.some(k => s.includes(normalizeDesc(k)))) return false
  // 적금·청약 납입은 이체가 맞다(계좌로 옮기는 돈) → 예외에서 제외
  if (/적금|청약|저축|도약/.test(s)) return true
  return !NOT_TRANSFER_KW.some(k => s.includes(normalizeDesc(k)))
}

// ── 사전 매칭 ────────────────────────────────────────────────────────────────
export interface LibHit {
  catId: string
  matched: string   // 적중한 키워드 (추천 이유 표시용)
}

/**
 * 적요에서 카테고리 후보를 점수순(적중 키워드가 긴 순)으로 반환.
 * 같은 catId는 한 번만 나온다.
 */
export function matchLibrary(desc: string, txType: string, type: DescType, limit = 3): LibHit[] {
  const s = normalizeDesc(desc + ' ' + txType)
  if (!s) return []

  const best = new Map<string, { len: number; matched: string }>()
  for (const rule of DESC_LIBRARY) {
    if (rule.type !== type) continue
    for (const kw of rule.kw) {
      const k = normalizeDesc(kw)
      if (!k || !s.includes(k)) continue
      const prev = best.get(rule.catId)
      if (!prev || k.length > prev.len) best.set(rule.catId, { len: k.length, matched: kw })
    }
  }
  return [...best.entries()]
    .sort((a, b) => b[1].len - a[1].len)
    .slice(0, limit)
    .map(([catId, v]) => ({ catId, matched: v.matched }))
}
